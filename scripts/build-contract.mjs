// Builds the checked-in artifacts with the exact compiler release.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

process.chdir(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'));

const versions = {
  legacy: { contract: 'FlashArb', output: 'artifact.ts', symbol: 'FLASH_ARB' },
  v2: { contract: 'FlashArbV2', output: 'artifact-v2.ts', symbol: 'FLASH_ARB_V2' },
};
const target = process.argv[2] ?? 'all';
if (target !== 'all' && !Object.hasOwn(versions, target)) throw new Error('Use npm run build:contract -- legacy|v2|all');
const compiler = process.env.SOLC || 'solc';
const release = '0.8.26+commit.8a97fa7a';
const version = execFileSync(compiler, ['--version'], { encoding: 'utf8' }).match(/Version: (\S+)/)?.[1];
if (!version?.startsWith(`${release}.`) && version !== release) throw new Error(`Expected Solidity ${release}, received ${version ?? 'unknown'}`);

for (const [name, spec] of Object.entries(versions)) {
  if (target !== 'all' && target !== name) continue;
  const source = `contracts/${spec.contract}.sol`;
  const out = execFileSync(compiler, [
    '--via-ir', '--optimize', '--optimize-runs', '200', '--evm-version', 'cancun', '--combined-json', 'abi,bin,bin-runtime', source,
  ], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
  const c = JSON.parse(out).contracts[`${source}:${spec.contract}`];
  const abi = typeof c.abi === 'string' ? JSON.parse(c.abi) : c.abi;
  // Keep the legacy generated file byte-for-byte stable across platforms.
  const recorded = name === 'legacy' ? `${release}.Darwin.appleclang` : release;
  fs.writeFileSync(`src/mev/${spec.output}`,
    `// Generated by scripts/build-contract.mjs from ${source} (solc ${recorded}, via-ir, optimizer 200 runs, cancun). Do not edit.\n` +
    `export const ${spec.symbol}_ABI = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
    `export const ${spec.symbol}_BYTECODE = '0x${c.bin}' as const;\n\n` +
    `export const ${spec.symbol}_RUNTIME = '0x${c['bin-runtime']}' as const;\n`,
  );
  console.log(`${spec.contract} compiled with Solidity ${release}: ${c.bin.length / 2} bytes creation, ${c['bin-runtime'].length / 2} bytes runtime`);
}
