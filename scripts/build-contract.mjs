// Builds the checked-in FlashArbV2 artifact with the exact compiler release.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

process.chdir(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'));

const target = process.argv[2] ?? 'v2';
if (target !== 'v2' && target !== 'all') throw new Error('Use npm run build:contract');
const compiler = process.env.SOLC || 'solc';
const release = '0.8.26+commit.8a97fa7a';
const version = execFileSync(compiler, ['--version'], { encoding: 'utf8' }).match(/Version: (\S+)/)?.[1];
if (!version?.startsWith(`${release}.`) && version !== release) throw new Error(`Expected Solidity ${release}, received ${version ?? 'unknown'}`);

const source = 'contracts/FlashArbV2.sol';
const out = execFileSync(compiler, [
  '--via-ir', '--optimize', '--optimize-runs', '200', '--evm-version', 'cancun', '--combined-json', 'abi,bin,bin-runtime', source,
], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
const contract = JSON.parse(out).contracts[`${source}:FlashArbV2`];
const abi = typeof contract.abi === 'string' ? JSON.parse(contract.abi) : contract.abi;
fs.writeFileSync('src/mev/artifact-v2.ts',
  `// Generated by scripts/build-contract.mjs from ${source} (solc ${release}, via-ir, optimizer 200 runs, cancun). Do not edit.\n` +
  `export const FLASH_ARB_V2_ABI = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
  `export const FLASH_ARB_V2_BYTECODE = '0x${contract.bin}' as const;\n\n` +
  `export const FLASH_ARB_V2_RUNTIME = '0x${contract['bin-runtime']}' as const;\n`,
);
console.log(`FlashArbV2 compiled with Solidity ${release}: ${contract.bin.length / 2} bytes creation, ${contract['bin-runtime'].length / 2} bytes runtime`);
