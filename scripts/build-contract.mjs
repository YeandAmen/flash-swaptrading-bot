// Builds the checked-in FlashArb artifacts with the exact compiler release.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

process.chdir(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'));

const target = process.argv[2] ?? 'all';
if (!['v2', 'v3', 'proxy', 'logic', 'logic-v2', 'arbitrum', 'all'].includes(target)) throw new Error('Use npm run build:contract -- v2|v3|proxy|logic|logic-v2|arbitrum|all');
const compiler = process.env.SOLC || 'solc';
const release = '0.8.26+commit.8a97fa7a';
const version = execFileSync(compiler, ['--version'], { encoding: 'utf8' }).match(/Version: (\S+)/)?.[1];
if (!version?.startsWith(`${release}.`) && version !== release) throw new Error(`Expected Solidity ${release}, received ${version ?? 'unknown'}`);

for (const version of target === 'all' ? ['v2', 'v3', 'proxy', 'logic', 'logic-v2', 'arbitrum'] : [target]) {
  const suffix = version.toUpperCase().replace('-', '_');
  const name = ({ proxy: 'FlashArbProxy', logic: 'FlashArbLogic', 'logic-v2': 'FlashArbLogicV2', arbitrum: 'FlashArbArbitrum' })[version] ?? `FlashArb${suffix}`;
  const source = `contracts/${name}.sol`;
  const out = execFileSync(compiler, [
    '--via-ir', '--optimize', '--optimize-runs', '200', '--evm-version', 'cancun', '--combined-json', 'abi,bin,bin-runtime', source,
  ], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
  const contract = JSON.parse(out).contracts[`${source}:${name}`];
  const abi = typeof contract.abi === 'string' ? JSON.parse(contract.abi) : contract.abi;
  const file = version === 'arbitrum' ? 'src/arbitrum/artifact.ts' : `src/mev/artifact-${version}.ts`;
  const prefix = version === 'arbitrum' ? 'ARBITRUM_FLASH_ARB' : `FLASH_ARB_${suffix}`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file,
    `// Generated by scripts/build-contract.mjs from ${source} (solc ${release}, via-ir, optimizer 200 runs, cancun). Do not edit.\n` +
    `export const ${prefix}_ABI = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
    `export const ${prefix}_BYTECODE = '0x${contract.bin}' as const;\n\n` +
    `export const ${prefix}_RUNTIME = '0x${contract['bin-runtime']}' as const;\n`,
  );
  console.log(`${name} compiled with Solidity ${release}: ${contract.bin.length / 2} bytes creation, ${contract['bin-runtime'].length / 2} bytes runtime`);
}
