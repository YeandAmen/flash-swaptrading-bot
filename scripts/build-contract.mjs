// Compiles contracts/FlashArb.sol with the local solc (0.8.26, `brew install solidity`) and writes
// src/mev/artifact.ts, so the bot itself never needs a Solidity compiler. Run: npm run build:contract
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
const version = execFileSync('solc', ['--version'], { encoding: 'utf8' }).match(/Version: (\S+)/)?.[1] ?? '?';
const out = execFileSync(
  'solc',
  ['--via-ir', '--optimize', '--optimize-runs', '200', '--evm-version', 'cancun', '--combined-json', 'abi,bin,bin-runtime', 'contracts/FlashArb.sol'],
  { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }, // (solc warns that transient storage needs care: we clear it)
);
const c = JSON.parse(out).contracts['contracts/FlashArb.sol:FlashArb'];
const abi = typeof c.abi === 'string' ? JSON.parse(c.abi) : c.abi;
fs.mkdirSync('src/mev', { recursive: true });
fs.writeFileSync(
  'src/mev/artifact.ts',
  `// Generated by scripts/build-contract.mjs from contracts/FlashArb.sol (solc ${version}, via-ir, optimizer 200 runs, cancun). Do not edit.\n` +
    `export const FLASH_ARB_ABI = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
    `export const FLASH_ARB_BYTECODE = '0x${c.bin}' as const;\n\n` +
    `export const FLASH_ARB_RUNTIME = '0x${c['bin-runtime']}' as const;\n`,
);
console.log(`FlashArb compiled with solc ${version}: ${c.bin.length / 2} bytes creation code, ${c['bin-runtime'].length / 2} bytes runtime`);
